import { pgTable, serial, decimal, text, integer, boolean } from "drizzle-orm/pg-core";

export const settingsTable = pgTable("settings", {
  id: serial("id").primaryKey(),
  companyId: integer("company_id"),
  gstRate: decimal("gst_rate", { precision: 5, scale: 2 }).notNull().default("9"),
  smtpHost: text("smtp_host"),
  smtpPort: text("smtp_port"),
  smtpUser: text("smtp_user"),
  smtpPass: text("smtp_pass"),
  smtpFrom: text("smtp_from"),
  poPrefix: text("po_prefix").default("PO"),
  poCounter: integer("po_counter").default(0).notNull(),
  poSuffix: text("po_suffix").default(""),
  invPrefix: text("inv_prefix").default("INV"),
  invCounter: integer("inv_counter").default(0).notNull(),
  invSuffix: text("inv_suffix").default(""),
  qtPrefix: text("qt_prefix").default("QT"),
  qtCounter: integer("qt_counter").default(0).notNull(),
  qtSuffix: text("qt_suffix").default(""),
  doPrefix: text("do_prefix").default("DO"),
  doCounter: integer("do_counter").default(0).notNull(),
  doSuffix: text("do_suffix").default(""),
  soPrefix: text("so_prefix").default("SO"),
  soCounter: integer("so_counter").default(0).notNull(),
  soSuffix: text("so_suffix").default(""),
  grnPrefix: text("grn_prefix").default("GRN"),
  grnCounter: integer("grn_counter").default(0).notNull(),
  grnSuffix: text("grn_suffix").default(""),
  cnPrefix: text("cn_prefix").default("CN"),
  cnCounter: integer("cn_counter").default(0).notNull(),
  cnSuffix: text("cn_suffix").default(""),
  dnPrefix: text("dn_prefix").default("DN"),
  dnCounter: integer("dn_counter").default(0).notNull(),
  dnSuffix: text("dn_suffix").default(""),
  piPrefix: text("pi_prefix").default("PI"),
  piCounter: integer("pi_counter").default(0).notNull(),
  piSuffix: text("pi_suffix").default(""),
  pvPrefix: text("pv_prefix").default("PV"),
  pvCounter: integer("pv_counter").default(0).notNull(),
  pvSuffix: text("pv_suffix").default(""),
  siPrefix: text("si_prefix").default("STK"),
  siCounter: integer("si_counter").default(0).notNull(),
  siSuffix: text("si_suffix").default(""),
  igrPrefix: text("igr_prefix").default("IGR"),
  igrCounter: integer("igr_counter").default(0).notNull(),
  igrSuffix: text("igr_suffix").default(""),
  ginPrefix: text("gin_prefix").default("GIN"),
  ginCounter: integer("gin_counter").default(0).notNull(),
  ginSuffix: text("gin_suffix").default(""),
  stPrefix: text("st_prefix").default("ST"),
  stCounter: integer("st_counter").default(0).notNull(),
  stSuffix: text("st_suffix").default(""),
  saPrefix: text("sa_prefix").default("SA"),
  saCounter: integer("sa_counter").default(0).notNull(),
  saSuffix: text("sa_suffix").default(""),
  allowNegativeStock: boolean("allow_negative_stock").default(false).notNull(),
  autoDeductOnDo: boolean("auto_deduct_on_do").default(false).notNull(),
  lowStockWarning: decimal("low_stock_warning", { precision: 15, scale: 3 }).default("0"),
  defaultUom: text("default_uom").default("pcs"),
  bankDetails: text("bank_details"),
  termsAndConditions: text("terms_and_conditions"),
  quotationTerms: text("quotation_terms"),
  // Voucher workflow defaults
  defaultVerifierId: integer("default_verifier_id"),
  defaultApproverId: integer("default_approver_id"),
  defaultPaidById: integer("default_paid_by_id"),
});

export type SettingsRecord = typeof settingsTable.$inferSelect;
