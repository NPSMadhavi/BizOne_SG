export function resolveLayout(reportId: string): InventoryReportLayout {
  if (reportId === "batch_report") return "batch_wise";
  if (reportId === "expiry_report") return "expiry_wise";
  if (reportId === "stock_summary") return "stock_wise";
  return "generic";
}

