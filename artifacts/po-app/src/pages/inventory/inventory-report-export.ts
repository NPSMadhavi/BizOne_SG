export function exportGenericPdf(meta: ReportMeta, rows: Record<string, string | number>[]) {
  const doc = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  let startY = drawHeader(doc, { ...meta, layout: "generic" }, pageWidth);
  const keys = Object.keys(rows[0] || {});
  (doc as any).autoTable({
    startY,
    head: [keys],
    body: rows.map((r) => keys.map((k) => String(r[k] ?? ""))),
    theme: "striped",
    styles: { fontSize: 7, cellPadding: 1.8 },
    headStyles: { fillColor: layoutColor("generic"), textColor: 255, fontStyle: "bold" },
    alternateRowStyles: { fillColor: [249, 250, 251] },
    margin: { left: 14, right: 14, bottom: 16 },
  });
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    drawFooter(doc, pageWidth, pageHeight, i, pageCount);
  }
  doc.save(`${safeFile(meta.reportTitle)}-${meta.reportDate}.pdf`);
}

function autoFitCols(aoa: (string | number)[][]): XLSX.ColInfo[] {
  const colCount = aoa.reduce((max, row) => Math.max(max, row.length), 0);
  const widths: number[] = Array.from({ length: colCount }, () => 10);

  for (const row of aoa) {
    for (let i = 0; i < row.length; i++) {
      const cell = row[i];
      const len = cell == null || cell === "" ? 0 : String(cell).length;
      if (len + 2 > widths[i]) widths[i] = len + 2;
    }
  }

  return widths.map((wch) => ({ wch: Math.min(Math.max(wch, 10), 48) }));
}

function sheetFromAoa(aoa: (string | number)[][]) {
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  ws["!cols"] = autoFitCols(aoa);
  return ws;
}

function excelMetaRows(meta: ReportMeta): (string | number)[][] {
  const rows: (string | number)[][] = [
    ["INVENTORY REPORTS"],
    ["Print / PDF / Excel Friendly Reports"],
    [],
    [meta.companyName],
  ];
  if (meta.companyAddress) rows.push([meta.companyAddress]);
  rows.push(
    [],
    [meta.reportTitle.toUpperCase()],
    [],
    ["Date Range", `${fmtDate(meta.dateFrom)} - ${fmtDate(meta.dateTo)}`],
    ["Report Date", fmtDate(meta.reportDate)],
    ["Warehouse", meta.warehouse || "All Warehouses"],
    ["Generated By", meta.generatedBy],
  );
  if (meta.category) rows.push(["Category", meta.category]);
  rows.push([]);
  return rows;
}

