function money(n: number) {
  return Number(n || 0).toLocaleString("en-SG", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

function qty(n: number) {
  return Number(n || 0).toLocaleString("en-SG", { minimumFractionDigits: 0, maximumFractionDigits: 3 });
}

function fmtDate(iso: string) {
  if (!iso) return "-";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) {
    // already dd/mm/yyyy or plain string
    if (/^\d{4}-\d{2}-\d{2}/.test(iso)) {
      const [y, m, day] = iso.slice(0, 10).split("-");
      return `${day}/${m}/${y}`;
    }
    return iso;
  }
  const day = String(d.getDate()).padStart(2, "0");
  const m = String(d.getMonth() + 1).padStart(2, "0");
  return `${day}/${m}/${d.getFullYear()}`;
}

function layoutColor(layout: InventoryReportLayout): [number, number, number] {
  void layout;
  return [59, 130, 246]; // light blue (#3B82F6)
}

function safeFile(name: string) {
  return name.replace(/[^\w\-]+/g, "-").replace(/-+/g, "-").toLowerCase();
}

function drawHeader(doc: jsPDF, meta: ReportMeta, pageWidth: number) {
  const color = layoutColor(meta.layout);
  doc.setFillColor(...color);
  doc.rect(0, 0, pageWidth, 18, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(11);
  doc.setFont("helvetica", "bold");
  doc.text("INVENTORY REPORTS", 14, 8);
  doc.setFontSize(8);
  doc.setFont("helvetica", "normal");
  doc.text("Print / PDF / Excel Friendly Reports", 14, 14);

  doc.setTextColor(17, 24, 39);
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.text(meta.companyName || "Company", 14, 28);

  if (meta.companyAddress) {
    doc.setFontSize(8);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(75, 85, 99);
    doc.text(meta.companyAddress, 14, 33);
  }

  // Title bar
  const titleY = meta.companyAddress ? 38 : 34;
  doc.setFillColor(...color);
  doc.roundedRect(14, titleY, pageWidth - 28, 10, 1, 1, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.text(meta.reportTitle.toUpperCase(), 18, titleY + 6.5);

  // Meta grid
  const metaY = titleY + 16;
  doc.setTextColor(55, 65, 81);
  doc.setFontSize(8);
  doc.setFont("helvetica", "normal");
  const left = [
    `Date Range : ${fmtDate(meta.dateFrom)} - ${fmtDate(meta.dateTo)}`,
    `Report Date : ${fmtDate(meta.reportDate)}`,
    `Warehouse : ${meta.warehouse || "All Warehouses"}`,
  ];
  const right = [
    `Generated By : ${meta.generatedBy}`,
    meta.category ? `Category : ${meta.category}` : "",
  ].filter(Boolean);

  left.forEach((line, i) => doc.text(line, 14, metaY + i * 5));
  right.forEach((line, i) => doc.text(line, pageWidth / 2 + 10, metaY + i * 5));

  return metaY + Math.max(left.length, right.length) * 5 + 4;
}

function drawFooter(doc: jsPDF, pageWidth: number, pageHeight: number, page: number, total: number) {
  doc.setFontSize(7);
  doc.setTextColor(107, 114, 128);
  doc.setFont("helvetica", "normal");
  doc.text(`Page ${page} of ${total}`, pageWidth - 14, pageHeight - 8, { align: "right" });
}

export function exportStockWisePdf(meta: ReportMeta, rows: StockWiseRow[]) {
  const doc = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  let startY = drawHeader(doc, { ...meta, layout: "stock_wise" }, pageWidth);

  const body = rows.map((r) => [
    r.sno,
    r.itemCode,
    r.itemName,
    r.uom,
    qty(r.openingQty),
    qty(r.purchaseQty),
    qty(r.salesQty),
    qty(r.adjustQty),
    qty(r.closingQty),
    money(r.unitCost),
    money(r.stockValue),
    money(r.gst),
    money(r.totalValue),
  ]);

  const totals = rows.reduce(
    (a, r) => ({
      opening: a.opening + r.openingQty,
      purchase: a.purchase + r.purchaseQty,
      sales: a.sales + r.salesQty,
      adjust: a.adjust + r.adjustQty,
      closing: a.closing + r.closingQty,
      value: a.value + r.stockValue,
      gst: a.gst + r.gst,
      total: a.total + r.totalValue,
    }),
    { opening: 0, purchase: 0, sales: 0, adjust: 0, closing: 0, value: 0, gst: 0, total: 0 },
  );

  (doc as any).autoTable({
    startY,
    head: [[
      "S.No.", "Item Code", "Item Name", "UOM",
      "Opening Qty", "Purchase Qty", "Sales Qty", "Adjust Qty", "Closing Qty",
      "Unit Cost (SGD)", "Stock Value (SGD)", "GST 9%", "Total Value (SGD)",
    ]],
    body,
    foot: [[
      "", "", "GRAND TOTAL", "",
      qty(totals.opening), qty(totals.purchase), qty(totals.sales), qty(totals.adjust), qty(totals.closing),
      "", money(totals.value), money(totals.gst), money(totals.total),
    ]],
    theme: "striped",
    styles: { fontSize: 7, cellPadding: 1.8, lineColor: [229, 231, 235], lineWidth: 0.1 },
    headStyles: { fillColor: layoutColor("stock_wise"), textColor: 255, fontStyle: "bold", fontSize: 7 },
    footStyles: { fillColor: [243, 244, 246], textColor: [17, 24, 39], fontStyle: "bold", fontSize: 7 },
    alternateRowStyles: { fillColor: [249, 250, 251] },
    margin: { left: 14, right: 14, bottom: 16 },
    didDrawPage: (data: any) => {
      if (data.pageNumber > 1) drawHeader(doc, { ...meta, layout: "stock_wise" }, pageWidth);
    },
  });

  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    drawFooter(doc, pageWidth, pageHeight, i, pageCount);
  }

  doc.save(`${safeFile(meta.reportTitle)}-${meta.reportDate}.pdf`);
}

